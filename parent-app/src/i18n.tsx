const dictionaries: Record<Locale, Partial<Record<MessageKey, string>>> = { en, gu };

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem('suraksha.locale');
    if (stored === 'en' || stored === 'gu') return stored;
    return navigator.language?.toLowerCase().startsWith('gu') ? 'gu' : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    localStorage.setItem('suraksha.locale', locale);
  }, [locale]);

  const setLocale = useCallback((next: Locale) => setLocaleState(next), []);

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => {
      const template = dictionaries[locale][key] ?? en[key] ?? key;
      if (!vars) return template;
      return Object.entries(vars).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, String(v)), template);
    },
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

export type { Locale as AppLocale };
